class Article {
  final int id;
  final String title;
  final String description;
  final String content;
  final String image;
  final String category;
  final String author;
  final DateTime date;

  Article({
    required this.id,
    required this.title,
    required this.description,
    required this.content,
    required this.image,
    required this.category,
    required this.author,
    required this.date,
  });
}


